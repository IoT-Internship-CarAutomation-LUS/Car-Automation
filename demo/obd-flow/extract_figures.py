# extract_figures.py -- pull the evidence figures for /flow/ out of the internship report.
#
#   python demo/obd-flow/extract_figures.py
#
# Reads demo/_private/Shahid Final.pdf (git-ignored, never committed) and writes ONLY the
# figures listed below to demo/obd-flow/img/ (photos as JPG, screenshots as PNG, max 1600 px
# wide) plus img/figures.json with the captions exactly as printed in the report.
# No other page is touched: no title page, no photo/bio page, no Figure 5.6 map.

import io
import json
import sys
from pathlib import Path

import pymupdf
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
PDF = ROOT / "demo" / "_private" / "Shahid Final.pdf"
OUT = ROOT / "demo" / "obd-flow" / "img"

# (1-based page, image index on that page, file stem, figure number, caption, kind)
FIGURES = [
    (45, 0, "fig5-11-capture-in-fronx", "5.11", "Live Capture Inside the Fronx, 10 July", "photo"),
    (27, 0, "fig4-1-obd-pins", "4.1", "OBD-II Connector Pin Layout and the Pins Used", "diagram"),
    (30, 0, "fig4-3-request-reply", "4.3", "Path of an Engine Speed Request and Its Reply", "diagram"),
    (48, 0, "fig5-13-elm327-init", "5.13", "Raspberry Pi: ELM327 Initialisation and First Combined OBD and GPS Reading", "screen"),
    (46, 0, "fig5-12-parts", "5.12", "Parts for the In-Car Unit: Raspberry Pi 4, ESP32 Boards, GPS and CAN Modules", "photo"),
    (57, 0, "fig6-2-raw-decoded-packed", "6.2", "Raspberry Pi: Raw Replies, Decoded Values and the Packed 32-Byte Packet", "screen"),
    (37, 0, "fig5-4-board2-gps", "5.4", "Board 2 with GPS, CAN and GSM Modules", "photo"),
    (58, 0, "fig6-3-pi-forwarding", "6.3", "Raspberry Pi: Capture Running with Packet Forwarding Enabled", "screen"),
    (58, 1, "fig6-4-laptop-receiver", "6.4", "Laptop Receiver: Every Packet Decoded and Passing its CRC", "screen"),
    (60, 0, "fig6-5-dashboard-real-rpm", "6.5", "Dashboard Showing a Real Engine Speed Reading on 14 July", "screen"),
]


def main():
    if not PDF.exists():
        sys.exit(f"Report not found: {PDF} (it lives only in the git-ignored demo/_private/)")
    OUT.mkdir(parents=True, exist_ok=True)
    doc = pymupdf.open(PDF)
    meta = {}
    for page, idx, stem, num, caption, kind in FIGURES:
        xref = doc[page - 1].get_images(full=True)[idx][0]
        raw = doc.extract_image(xref)
        img = Image.open(io.BytesIO(raw["image"]))
        if img.mode in ("P", "LA", "RGBA") and kind == "photo":
            img = img.convert("RGB")
        if img.width > 1600:
            img = img.resize((1600, round(img.height * 1600 / img.width)), Image.LANCZOS)
        if kind == "photo":
            name = stem + ".jpg"
            img.convert("RGB").save(OUT / name, "JPEG", quality=82, optimize=True, progressive=True)
        else:
            name = stem + ".png"
            img.save(OUT / name, "PNG", optimize=True)
        meta[stem] = {"file": "img/" + name, "figure": num, "caption": caption,
                      "page": page, "width": img.width, "height": img.height}
        print(f"p{page} -> {name} ({img.width}x{img.height}, {(OUT / name).stat().st_size // 1024} KB)")
    (OUT / "figures.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
    js = OUT.parent / "js" / "figures.js"
    js.parent.mkdir(parents=True, exist_ok=True)
    js.write_text("// Generated by demo/obd-flow/extract_figures.py -- captions exactly as printed in the report.\n"
                  "window.FLOW_FIGURES = " + json.dumps(meta, separators=(",", ":")) + ";\n", encoding="utf-8")


if __name__ == "__main__":
    main()
